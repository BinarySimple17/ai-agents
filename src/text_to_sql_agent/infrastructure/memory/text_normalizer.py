"""Нормализация текста для гибридного поиска — один хелпер на upsert и запрос
(S26 Task 1; D-026 доп. 1(2)).

Зачем (числа-якорь D-026): комбинирующий акут U+0301 — не буква, и
`to_tsvector('russian', …)` режет термин пополам («Кана́рские» → «кан»+«рские»);
замер родственного проекта на RuBQ: nDCG@10 0.3634 → 0.4306 после снятия акута.
ё/е — разные термы для FTS, хотя в бизнес-вопросах эквивалентны.

Регистр НЕ трогается — `to_tsvector` приводит лексемы сам (D-026); ё→е делается
в обоих регистрах, чтобы замена не зависела от позиции буквы в слове.

Хелпер — чистая функция без IO/LLM (правила домена чистоты соблюдены: он лежит
рядом с адаптером памяти, потому что обслуживает формат хранения, а не бизнес).
"""

# Комбинирующий акут (combining acute accent) — диакритика поверх предыдущей
# буквы, самостоятельным символом кодировки не является
_COMBINING_ACUTE = "́"

# Ё→е в обоих регистрах: to_tsvector приводит регистр сам, но замена пары
# символов симметрична и не зависит от того, что встретилось в тексте первым
_ACUTE_MAP = {"ё": "е", "Ё": "Е"}


def normalize_text(text: str) -> str:
    """Снимает комбинирующий акут U+0301 и заменяет ё→е (регистр не меняется).

    Применяется: (1) к контенту ДО записи — generated-колонка content_tsv берёт
    content как есть, конфиг в ней литералом (immutable, Ловушки-3), поэтому
    нормализация возможна только до INSERT; (2) к тексту запроса FTS-ноги —
    до plainto_tsquery (Ловушки-5: одна реализация на оба места).
    """
    normalized = text.replace(_COMBINING_ACUTE, "")
    for source, target in _ACUTE_MAP.items():
        normalized = normalized.replace(source, target)
    return normalized
