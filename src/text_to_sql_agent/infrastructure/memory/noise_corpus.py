"""Генератор шумового корпуса-дистрактора (S26 Task 4; D-026 доп. 1(3), BL-007).

Зачем: «топ-5 среди 7 таблиц» — тривиальный замер; шум должен ранжироваться
ВМЕСТЕ с реальными документами, иначе hit@5 обманчиво высок (точка владельца
в D-026). Дистрактор ДЕЛИТ общий признак с целью (упоминает ту же таблицу и
её доменную лексику — иначе задача вырождается, Ловушки-4), но НЕ является
знанием: `doc_kind='noise'`, `table_name NULL`, в промпт не попадает (фильтр
при сборке контекста — presentation-слой; ruling N2: referenced_tables
объявляются по упоминаниям — guard универсален, NFR-4 без исключений).

Детерминизм: только stdlib, фиксированный сид, самопроверка двойной генерацией
(побитово тот же результат — тест). Шум — измерительная инфраструктура бенча,
не знание: автогенерация здесь не нарушает запрет «автонаполнения» ADR-003 §4,
который про curаторские знания (ddl/glossary/few_shot/relationship).
"""

import random
from collections.abc import Sequence

from text_to_sql_agent.application.ports.vector_store import DocKind, KnowledgeDocument

# Размер корпуса: ~300 (D-026) — на два порядка больше кураторского (~30),
# мал для «топ-5 среди 7 таблиц», но ещё честен для локального бенча
NOISE_CORPUS_SIZE = 300

# Фиксированный сид: дата старта сессии S26 — корпус воспроизводим побитово
NOISE_SEED = 20261121

# Доменная лексика таблицы — «общий признак с целью» (D-026 доп. 1(3)): дистрактор
# о той же предметной области, что и знание по таблице. ОСТОРОЖНО: слова здесь —
# русская лексика, БЕЗ идентификаторов таблиц (guard проверяет \bимя\b —
# «заказ» не матчится на «orders»; имена чужих таблиц в шаблонах запрещены)
_TABLE_VOCAB: dict[str, str] = {
    "customers": "клиент, страна клиента, регистрация, новый покупатель",
    "campaigns": "рекламная кампания, канал привлечения, охват, старт кампании",
    "products": "товар, категория товара, прайс-лист, наименование",
    "orders": "заказ, статус заказа, отмена, сумма заказа, дата заказа",
    "order_items": "позиция заказа, количество, цена продажи, состав корзины",
    "employees": "сотрудник, отдел, штатное расписание, должность",
    "bonuses": "премия, премиальный период, начисление, размер премии",
}

# Шаблоны предложений: {a} — выбранная таблица, {b} — вторая (если есть),
# {n} — номер документа, {vocab} — доменная лексика. Ни один шаблон не называет
# таблицы вне подстановок (guard check_declared_references: упоминания ⊆
# declared — ruling N2). Однотабличные шаблоны не используют {b}: у
# однотабличного дистрактора не появляется текст «таблицы X и X»
_SINGLE_TABLE_TEMPLATES = (
    "Служебная заметка {n}: черновик регламента по таблице {a}, раздел {n}. "
    "Положения черновика не согласованы, часть пунктов устарела.",
    "Протокол встречи {n}: обсудили данные таблицы {a} ({vocab}); "
    "сроки доработки уточняются, ответственный не назначен.",
    "Замечание аудита {n}: в таблице {a} требуются уточнения справочников; "
    "рекомендации аудита в работе, приоритет средний.",
    "Заявка на доработку {n}: отчётность по таблице {a} не покрывает "
    "запросы бизнеса ({vocab}); предлагается черновик изменений.",
    "Технический долг {n}: миграция справочников таблицы {a}; "
    "оценка предварительная, риски описаны частично.",
)

# Кросс-табличные: {a} и {b} — пара выбранных таблиц
_CROSS_TABLE_TEMPLATES = (
    "Черновик инструкции {n}: порядок сверки данных таблиц {a} и {b}; "
    "инструкция не утверждена, приведена для обсуждения.",
    "Заметка планирования {n}: по таблицам {a} и {b} готовится "
    "расширенная отчётность ({vocab}); объём и сроки уточняются.",
    "Протокол сверки {n}: расхождения между {a} и {b} описаны частично; "
    "предлагается общий справочник признаков.",
    "Черновик аудита {n}: связность данных таблиц {a} и {b}; "
    "выводы предварительные, выборка не финальная.",
)

_HEADER_TEMPLATE = "[шум: {tables}] "

# Фолбэк для таблицы каталога без кураторской лексики: дистрактор всё равно
# делит признак с целью (имя таблицы в заголовке/тексте — якорь FTS-ноги).
# Новая бизнес-таблица в каталоге agent_data_sources НЕ требует правки
# генератора (обещание BL-009 M1: каталог — SoT) — KeyError здесь ломал бы
# индексацию молча для make check (критическое замечание ревью S26 I2)
_FALLBACK_VOCAB = "данные таблицы, регламенты, отчётность"


def generate_noise_corpus(
    business_tables: Sequence[str], *, model_version: str
) -> list[KnowledgeDocument]:
    """~300 дистракторов: детерминированно (фиксированный сид, только stdlib).

    Каждый дистрактор объявляет `referenced_tables` по фактическим упоминаниям
    (ruling N2 S26) — guard прав проходит без исключений; `table_name NULL`
    (D-026: шум не привязан к якорю-таблице). Префикс-заголовок «[шум: …]» —
    якорь имени таблицы для FTS-ноги (ACCURACY §6.2), как у кураторских чанков.
    """
    if len(business_tables) < 2:
        raise ValueError(
            f"для шумового корпуса нужно ≥ 2 таблиц, получено {len(business_tables)} — "
            "дистрактор делит признак с целью (кросс-табличные варианты)"
        )
    rng = random.Random(NOISE_SEED)
    docs: list[KnowledgeDocument] = []
    for i in range(NOISE_CORPUS_SIZE):
        # 2/3 дистрактора кросс-табличные (требование D-026: общий признак с
        # целью — у кураторских знаний кросс-табличных большинство)
        table_count = 2 if i % 3 != 0 else 1
        tables = sorted(rng.sample(sorted(business_tables), table_count))
        vocab = _TABLE_VOCAB.get(tables[0], _FALLBACK_VOCAB)
        pool = _SINGLE_TABLE_TEMPLATES if table_count == 1 else _CROSS_TABLE_TEMPLATES
        template = pool[i % len(pool)]
        body = template.format(
            a=tables[0],
            b=tables[1] if len(tables) > 1 else tables[0],
            n=f"#{i + 1:04d}",
            vocab=vocab,
        )
        content = _HEADER_TEMPLATE.format(tables=", ".join(tables)) + body
        docs.append(
            KnowledgeDocument(
                doc_kind=DocKind.NOISE,
                table_name=None,
                referenced_tables=tables,
                content=content,
                model_version=model_version,
                source_ref=f"noise:{i + 1:04d}",
            )
        )
    return docs
